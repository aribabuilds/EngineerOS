// Runs before dev/build (see package.json "predev"/"prebuild"). Pulls real
// values from git so nothing on the site is a hardcoded, fake "recency"
// signal. Writes src/lib/buildInfo.generated.ts, which is gitignored and
// regenerated on every run.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "..", "src", "lib", "buildInfo.generated.ts");

function git(cmd, fallback = null) {
  try {
    const out = execSync(`git ${cmd}`, { cwd: join(__dirname, ".."), encoding: "utf8" }).trim();
    return out || fallback;
  } catch {
    return fallback;
  }
}

const commitHash = git("rev-parse --short HEAD");
const buildDate = new Date().toISOString().slice(0, 10);
const briefpilotLastUpdated = git(
  'log -1 --format=%cd --date=short -- src/app/work/briefpilot/page.tsx',
);

const lines = [
  "// AUTO-GENERATED by scripts/generate-build-info.mjs. Do not edit by hand.",
  "// Regenerated on every `npm run dev` / `npm run build` (see package.json).",
  "export interface BuildInfo {",
  "  commitHash: string | null;",
  "  buildDate: string;",
  "  briefpilotLastUpdated: string | null;",
  "}",
  "",
  "export const buildInfo: BuildInfo = {",
  `  commitHash: ${commitHash ? JSON.stringify(commitHash) : "null"},`,
  `  buildDate: ${JSON.stringify(buildDate)},`,
  `  briefpilotLastUpdated: ${briefpilotLastUpdated ? JSON.stringify(briefpilotLastUpdated) : "null"},`,
  "};",
  "",
];

writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`[generate-build-info] commit=${commitHash ?? "unknown"} date=${buildDate}`);
